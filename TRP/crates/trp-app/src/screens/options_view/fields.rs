    /// The group field this one is a part of, if any: while that is off,
    /// so is this, whatever its own says (`Features::effective`).
    pub(super) fn group(self) -> Option<Self> {
        match self {
            Self::StaminaDrain | Self::Exhaustion => Some(Self::Stamina),
            Self::UnderbarrelLauncher => Some(Self::WeaponHandling),
            Self::MovementSounds | Self::HandsSounds | Self::ShotSounds | Self::WorldSounds | Self::HeadgearHearing => Some(Self::Sounds),
            Self::MuzzleFlash | Self::Particles | Self::Tracers | Self::SpentCases | Self::MagazineRounds | Self::FaceShieldMask | Self::FaceShieldCracks => Some(Self::VisualEffects),
            _ => None,
        }
    }

    pub(super) fn get(self, features: &Features) -> bool {
        *self.slot(&mut features.clone())
    }
