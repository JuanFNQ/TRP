//! Parsing the command line into the app's options.

use super::*;

mod character_args;
mod display_args;
mod input_args;

pub(super) fn parse_options(settings: &trp_data::PlayerSettings) -> Options {
    let mut options = default_options(settings);
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        let taken = character_args::character(&mut options, &arg, &mut args)
            || input_args::input(&mut options, &arg, &mut args)
            || display_args::display(&mut options, &arg, &mut args);
        if !taken {
            eprintln!("ignoring unknown argument {arg}");
        }
    }
    options
}

